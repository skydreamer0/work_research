const toggles = Array.from(document.querySelectorAll("[data-version-toggle]"));

function renderList(target, items, renderItem) {
  target.innerHTML = "";
  items.forEach((item) => {
    target.appendChild(renderItem(item));
  });
}

function renderSections(versionKey) {
  const version = contentByVersion[versionKey];

  elements.heroTitle.textContent = version.heroTitle;
  elements.heroSubtitle.textContent = version.heroSubtitle;
  elements.heroNote.textContent = version.heroNote;
  elements.stanceTitle.textContent = version.stance.title;
  elements.stanceBody.textContent = version.stance.body;
  elements.overviewTitle.textContent = version.overview.title;
  elements.overviewSummary.textContent = version.overview.summary;
  elements.diseaseTitle.textContent = version.disease.title;
  elements.diseaseSummary.textContent = version.disease.summary;
  elements.diseaseCallout.textContent = version.disease.callout;
  elements.evidenceSummaryTitle.textContent = version.evidence.title;
  elements.evidenceSummaryBody.textContent = version.evidence.body;
  elements.safetyTitle.textContent = version.safety.title;
  elements.safetySummary.textContent = version.safety.summary;

  renderList(elements.readingPath, version.path, (item) => {
    const li = document.createElement("li");
    li.textContent = item;
    return li;
  });

  renderList(elements.audienceList, version.overview.audiences, (item) => {
    const li = document.createElement("li");
    li.textContent = item;
    return li;
  });

  renderList(elements.impactFlow, version.impactFlow, (item) => {
    const article = document.createElement("article");
    article.className = "flow-card";
    article.innerHTML = `<h3>${item.title}</h3><p>${item.body}</p>`;
    return article;
  });

  renderList(elements.mechanismColumns, version.mechanism, (item) => {
    const article = document.createElement("article");
    article.className = "mechanism-card";
    article.innerHTML = `<h3>${item.title}</h3><p>${item.body}</p>`;
    return article;
  });

  renderList(elements.metricCards, version.evidence.metrics, (item) => {
    const article = document.createElement("article");
    article.className = "metric-card";
    article.innerHTML = `
      <span class="metric-label">${item.label}</span>
      <strong class="metric-value">${item.value}</strong>
    `;
    return article;
  });

  renderList(elements.evidenceBars, version.evidence.bars, (item) => {
    const article = document.createElement("article");
    article.className = "bar-item";
    article.innerHTML = `
      <div class="bar-meta">
        <span>${item.label}</span>
        <span>${item.note}</span>
      </div>
      <div class="bar-track">
        <div class="bar-fill" style="width: ${item.value}%"></div>
      </div>
    `;
    return article;
  });

  renderList(elements.guardrailList, version.safety.guardrails, (item) => {
    const li = document.createElement("li");
    li.textContent = item;
    return li;
  });

  renderList(elements.practicalCards, version.practical, (item) => {
    const article = document.createElement("article");
    const chipClass = item.caution ? "status-chip is-caution" : "status-chip";
    article.className = "practical-card";
    article.innerHTML = `
      <span class="${chipClass}">${item.status}</span>
      <h3>${item.title}</h3>
      <p>${item.body}</p>
    `;
    return article;
  });

  renderList(elements.takeawayCards, version.takeaways, (item) => {
    const article = document.createElement("article");
    article.className = "takeaway-card";
    article.innerHTML = `<h3>${item.title}</h3><p>${item.body}</p>`;
    return article;
  });

  toggles.forEach((button) => {
    const isActive = button.dataset.versionToggle === versionKey;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  document.body.dataset.version = versionKey;
}

toggles.forEach((button) => {
  button.addEventListener("click", () => {
    renderSections(button.dataset.versionToggle);
  });
});

renderSections("internal");
